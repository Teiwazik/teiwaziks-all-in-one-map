#!/usr/bin/env python3
"""Builds megamap's mixin bundle and packs it.

1. Generates mixins/megamap/runtime.rs, the bundle's one support module, from src/glue.rs with
   src/engine/*.rs inlined as `mod engine { pub mod baker { ... } ... }`. horizon-mixins adds it to
   crates/horizon-client/src/game.rs as `mod native_megamap` and wants it self-contained: no file
   attributes, no `mod x;` without a body, no #[path], no include!. Those are checked here too.
2. dist/megamap-<version>.hnmod: horizon-native.json + mixins/megamap/** (the native mod alone;
   this is what the launcher and the RT build take).
3. dist/megamap-<version>.hmod: the same plus horizon-mod.toml and assets/megamap/** (the GUI
   textures, tools/gen_art.py). Optional: megamap draws plain shapes without them.

Refuses to pack when the ids, versions or Horizon revisions disagree, when the manifest has no
module or injection, when a helper named by an injection is missing, or when a bundle file would
be rejected by the registry (anything but .rs/.toml under mixins/). Then validate with:
  cargo-horizon-mod check dist/megamap-<version>.hnmod
"""

import json
import os
import re
import sys
import tomllib
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXED_TIME = (2026, 1, 1, 0, 0, 0)  # reproducible archives
GENERATED = "// GENERATED by tools/pack.py from src/glue.rs and src/engine/*.rs. Edit those, not this.\n"


def read(path):
    with open(os.path.join(ROOT, path), "rb") as f:
        return f.read()


def runtime_source():
    glue = read("src/glue.rs").decode()
    engine_mod = read("src/engine/mod.rs").decode()
    names = re.findall(r"^pub mod (\w+);", engine_mod, re.M)
    if not names:
        sys.exit("pack: src/engine/mod.rs lists no `pub mod x;`")
    parts = []
    for name in names:
        body = read(f"src/engine/{name}.rs").decode()
        # Not re-indented: that would change any string literal that spans lines.
        parts.append(f"pub mod {name} {{\n{body}}}\n")
    engine = "#[allow(dead_code)]\nmod engine {\n" + "\n".join(parts) + "}\n"
    if glue.count("\nmod engine;\n") != 1:
        sys.exit("pack: src/glue.rs must have exactly one `mod engine;` line")
    out = GENERATED + glue.replace("\nmod engine;\n", "\n" + engine, 1)
    # What horizon-mixins refuses in a support module (horizon-mixins-core modules.rs).
    first = next((l for l in out.splitlines() if l.strip() and not l.lstrip().startswith("//") or l.startswith("//!")), "")
    if first.startswith(("#!", "//!")):
        sys.exit(f"pack: runtime.rs starts with a file attribute: {first!r}")
    for pat, what in [(r"^\s*(pub(\([^)]*\))?\s+)?mod\s+\w+\s*;", "`mod x;` without a body"),
                      (r"#\[path\b", "#[path]"), (r"\binclude(_str|_bytes)?!", "include!")]:
        m = re.search(pat, out, re.M)
        if m:
            sys.exit(f"pack: runtime.rs has {what}: {m.group(0)!r}")
    if re.search(r"\bunsafe\b", out):
        sys.exit("pack: runtime.rs uses unsafe; horizon-client is #![forbid(unsafe_code)]")
    return out.encode()


def walk(base, keep):
    out = []
    for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, base)):
        dirnames[:] = sorted(d for d in dirnames if d not in ("target", ".git"))
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
            if keep(rel):
                out.append(rel)
    return out


def write_zip(out, files):
    tmp = out + ".partial"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in files:
            info = zipfile.ZipInfo(name, FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16  # regular file; the reader refuses links
            z.writestr(info, data)
    os.replace(tmp, out)


def main():
    native = json.loads(read("horizon-native.json"))
    content = tomllib.loads(read("horizon-mod.toml").decode())
    mixin = tomllib.loads(read("mixins/megamap/horizon-mixin.toml").decode())
    mod_id, version = native["id"], native["version"]
    checks = {
        "horizon-mod.toml id": (content.get("id"), mod_id),
        "horizon-mod.toml version": (content.get("version"), version),
        "horizon-mixin.toml mod.id": (mixin.get("mod", {}).get("id"), mod_id),
        "horizon-mixin.toml mod.version": (mixin.get("mod", {}).get("version"), version),
        "horizon-mixin.toml horizon_revision": (mixin.get("compatibility", {}).get("horizon_revision"), native["horizon"]),
    }
    glue_version = re.search(r'const VERSION: &str = "([^"]*)";', read("src/glue.rs").decode())
    checks["src/glue.rs VERSION"] = (glue_version and glue_version.group(1), version)
    for what, (got, want) in checks.items():
        if got != want:
            sys.exit(f"pack: {what} is {got!r}, horizon-native.json says {want!r}")
    if "api" in mixin:
        sys.exit("pack: horizon-mixin.toml has [api]; horizon-mixins 0.6 takes modules and injections only")
    modules, injections = mixin.get("module", []), mixin.get("injection", [])
    if not modules or not injections:
        sys.exit("pack: horizon-mixin.toml needs at least one module and one injection")
    bdir = f"mixins/{mod_id}"
    with open(os.path.join(ROOT, bdir, "runtime.rs"), "wb") as f:
        f.write(runtime_source())
    for entry in modules + injections:
        src = entry.get("source") or entry.get("helper")
        if src and not os.path.isfile(os.path.join(ROOT, bdir, src)):
            sys.exit(f"pack: {entry['id']}: {src} is missing from {bdir}")
    ids = [i["id"] for i in injections]
    if len(set(ids)) != len(ids):
        sys.exit("pack: duplicate injection ids")

    bundle = walk(bdir, lambda r: r.endswith((".rs", ".toml")))
    skipped = [r for r in walk(bdir, lambda r: True) if r not in bundle]
    if len(bundle) >= 512:
        sys.exit(f"pack: {len(bundle)} bundle files, the registry allows 511 besides the manifest")
    os.makedirs(os.path.join(ROOT, "dist"), exist_ok=True)

    native_files = [("horizon-native.json", read("horizon-native.json"))] + [(r, read(r)) for r in bundle]
    out = os.path.join(ROOT, "dist", f"{mod_id}-{version}.hnmod")
    write_zip(out, native_files)
    print(f"wrote {out}: {len(bundle)} bundle files, {os.path.getsize(out)} bytes")

    assets = walk(f"assets/{mod_id}", lambda r: r.endswith((".png", ".json")))
    if assets:
        out = os.path.join(ROOT, "dist", f"{mod_id}-{version}.hmod")
        write_zip(out, native_files[:1] + [("horizon-mod.toml", read("horizon-mod.toml"))]
                  + [(r, read(r)) for r in assets] + native_files[1:])
        print(f"wrote {out}: {len(bundle)} bundle files, {len(assets)} assets, {os.path.getsize(out)} bytes")
    else:
        print("no assets (tools/gen_art.py): .hmod not written")
    for rel in skipped:
        print(f"  not packed (registry refuses it): {rel}")


if __name__ == "__main__":
    main()
